func NewMinecraft(loader, mcv, mlv, path string) XModloader {
	return &Minecraft{
		loader:        loader,
		minecraft:     mcv,
		loaderVersion: mlv,
		path:          path,
		client:        resty.New().SetHeader("User-Agent", "DeEarthX"),
	}
}

type Minecraft struct {
	loader        string
	minecraft     string
	loaderVersion string
	path          string
	client        *resty.Client
}

func (m *Minecraft) Setup() error {
	if err := m.eula(); err != nil {
		return err
	}

	bmclapi := utils.GlobalConfig.GetConfigValue("mirror.bmclapi")
	if bmclapi != true {
		return nil
	}

	switch m.loader {
	case "forge", "neoforge":
		return m.forgeSetup()
	case "fabric", "fabric-loader":
		return m.fabricSetup()
	}

	return nil
}

func (m *Minecraft) Installer() error {
	// Minecraft has no additional installer
	return nil
}

